// Builds the site assistant's knowledge base.
//
// Gathers the readable text from every public site page plus any hand-curated
// source files (e.g. Eric's companion-site content), and writes it into
// api/_lib/knowledge-base.js as a single string the assistant imports.
//
// The PDFs in landing/downloads are generated from these same pages, so they
// add no new information and are intentionally skipped.
//
//   Run:  node scripts/build-knowledge-base.mjs
//   Then: redeploy (the assistant reads the generated module at runtime).
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const LANDING = join(root, 'landing');
const SOURCES = join(LANDING, 'assistant', 'sources');
const OUT = join(root, 'api', '_lib', 'knowledge-base.js');

// Pages that are not public-facing informational content.
const SKIP_PAGES = new Set(['admin.html', 'index-b.html', 'equipment-application.html', 'campaign.html']);

function stripHtml(html) {
  let text = html
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<svg[\s\S]*?<\/svg>/gi, ' ')
    .replace(/<[^>]+>/g, ' ');
  text = text
    .replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'")
    .replace(/&mdash;/g, '—').replace(/&rarr;/g, '→').replace(/&hellip;/g, '…');
  return text.replace(/[ \t]+/g, ' ').replace(/\n\s*\n\s*\n+/g, '\n\n').replace(/\s+\n/g, '\n').trim();
}

function pageTitle(html, fallback) {
  const m = html.match(/<title>([\s\S]*?)<\/title>/i);
  return m ? stripHtml(m[1]).replace(/\s*\|\s*VillageServer Initiative\s*$/i, '').trim() : fallback;
}

const sections = [];

// 1. Site pages
const pages = readdirSync(LANDING).filter((f) => f.endsWith('.html') && !SKIP_PAGES.has(f)).sort();
for (const file of pages) {
  const html = readFileSync(join(LANDING, file), 'utf8');
  const text = stripHtml(html);
  if (text.length < 80) continue; // skip near-empty pages
  sections.push(`# Page: ${pageTitle(html, file)} (${file})\n\n${text}`);
}

// 2. Curated source files (companion site content, notes, extracted PDF text, …)
let sourceCount = 0;
if (existsSync(SOURCES)) {
  for (const file of readdirSync(SOURCES).filter((f) => /\.(md|txt)$/i.test(f)).sort()) {
    const text = readFileSync(join(SOURCES, file), 'utf8').trim();
    if (text) { sections.push(`# Source: ${basename(file)}\n\n${text}`); sourceCount++; }
  }
}

const knowledgeBase = sections.join('\n\n---\n\n');
const approxTokens = Math.round(knowledgeBase.length / 4);

const banner = `// AUTO-GENERATED by scripts/build-knowledge-base.mjs — do not edit by hand.\n` +
  `// Sources: ${pages.length} site pages + ${sourceCount} curated file(s). ` +
  `~${approxTokens.toLocaleString()} tokens.\n`;
writeFileSync(OUT, `${banner}export const KNOWLEDGE_BASE = ${JSON.stringify(knowledgeBase)};\n`);

// Ensure the sources folder exists so it's easy to drop companion content in.
if (!existsSync(SOURCES)) mkdirSync(SOURCES, { recursive: true });

console.log(`Knowledge base written to ${OUT}`);
console.log(`  ${pages.length} site pages, ${sourceCount} curated source file(s)`);
console.log(`  ${knowledgeBase.length.toLocaleString()} chars ≈ ${approxTokens.toLocaleString()} tokens`);
if (approxTokens > 150000) console.warn('  ⚠️  Approaching Haiku 200K context — consider trimming or a larger model.');
